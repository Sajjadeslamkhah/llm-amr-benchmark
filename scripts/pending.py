#!/usr/bin/env python3
"""List every outstanding item in the manuscript, generated from the files themselves.

    python scripts/pending.py

Writes manuscript/PENDING.md. Generated rather than maintained by hand, so it
cannot drift out of step with the drafts: a marker removed from a section
disappears from the list on the next run, and one added shows up without anyone
remembering to add it here.

A marker is any <mark>**[PENDING ...]**</mark> span in manuscript/*.md. The
"waiting on" column comes from WAITING below, matched on the marker's text, and
anything unmatched is listed as unassigned rather than guessed at.
"""
from __future__ import annotations

import re
from pathlib import Path

MD = Path("manuscript")
OUT = MD / "PENDING.md"
MARK = re.compile(r"<mark>\*\*\[(pending[^\]]*)\]\*\*</mark>", re.S | re.I)

# Substring of the marker text -> who has to act. Longest match wins.
WAITING = [
    ("osf", "investigator — deposit and cite the DOI"),
    ("zenodo", "investigator — deposit and cite the DOI"),
    ("adjudication", "two readers — blinded sheet already prepared"),
    ("breakpoint", "investigator — read the six values off the current EUCAST table"),
    ("eucast table", "investigator — read the six values off the current EUCAST table"),
    ("stricter mapping", "optional, post-hoc — not required for submission"),
    ("optional.", "optional, post-hoc — not required for submission"),
    ("doi", "investigator — deposit and cite the DOI"),
    ("plan tier", "investigator"),
]


def who(text: str) -> str:
    low = text.lower()
    hits = [(len(k), v) for k, v in WAITING if k in low]
    return max(hits)[1] if hits else "unassigned"


def main() -> None:
    rows = []
    for f in sorted(MD.glob("*.md")):
        if f.name == OUT.name:
            continue
        text = f.read_text()
        for m in MARK.finditer(text):
            line = text[: m.start()].count("\n") + 1
            # the note at the top of each draft explains the marker rather than being one
            start = text.rfind("\n", 0, m.start()) + 1
            if text[start:m.start()].lstrip().startswith(">") or text[start:].startswith(">"):
                continue
            if all(l.lstrip().startswith((">", "")) and l.lstrip().startswith(">")
                   for l in text[:m.start()].splitlines()[-1:] if l.strip()):
                continue
            body = re.sub(r"\s+", " ", m.group(1)).strip()
            body = re.sub(r"^pending:?\s*", "", body, flags=re.I) or "(no detail given)"
            # the nearest heading above it, for context
            heads = re.findall(r"^(#{1,3})\s+(.*)$", text[: m.start()], re.M)
            section = heads[-1][1] if heads else ""
            rows.append({"file": f.name, "line": line, "section": section,
                         "item": body, "waiting": who(body)})

    lines = ["# Outstanding items",
             "",
             "Generated by `scripts/pending.py` from the markers in the drafts. Do not edit:",
             "rerun the script after changing a draft.",
             ""]
    if not rows:
        lines += ["Nothing outstanding."]
    else:
        lines += [f"**{len(rows)} items.**", "",
                  "| # | Section | Item | Waiting on | Where |",
                  "|---|---|---|---|---|"]
        for i, r in enumerate(rows, 1):
            item = r["item"] if len(r["item"]) < 180 else r["item"][:177] + "..."
            lines.append(f"| {i} | {r['section']} | {item} | {r['waiting']} | "
                         f"`{r['file']}`:{r['line']} |")
        by = {}
        for r in rows:
            by.setdefault(r["waiting"], []).append(r)
        lines += ["", "## Grouped by who has to act", ""]
        for k in sorted(by):
            lines.append(f"**{k}** — {len(by[k])} item{'s' if len(by[k]) > 1 else ''}")
            for r in by[k]:
                lines.append(f"- {r['item'][:150]} (`{r['file']}`:{r['line']})")
            lines.append("")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT}: {len(rows)} items")
    for r in rows:
        print(f"  {r['file']}:{r['line']:<4} [{r['waiting']}] {r['item'][:80]}")


if __name__ == "__main__":
    main()
